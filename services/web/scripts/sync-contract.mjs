import { spawnSync } from 'node:child_process';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const webRoot = fileURLToPath(new URL('../', import.meta.url));
const repositoryRoot = path.resolve(webRoot, '../..');
const python = process.env.WEB_CONTRACT_PYTHON || path.join(repositoryRoot, '.venv', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python');
const exported = spawnSync(python, ['-X', 'utf8', '-m', 'services.agent_api.examples.export_web_openapi'], {
  cwd: repositoryRoot, encoding: 'utf8', timeout: 30_000, maxBuffer: 4 * 1024 * 1024,
});
if (exported.error || exported.status !== 0) {
  // Never forward subprocess stderr/environment values into artifacts or logs.
  throw new Error('Public OpenAPI export failed. Check the project Python environment.');
}
const openapi = JSON.parse(exported.stdout);
const schemaNames = Object.keys(openapi.components.schemas);
for (const name of ['AskRequest', 'AskResponse', 'ApiError', 'JsonValue']) {
  if (!schemaNames.includes(name)) throw new Error(`Missing public schema: ${name}`);
}

// Pydantic represents JsonValue as {}. Supply JSON's recursive value type,
// not an arbitrary JavaScript value; keep the canonical OpenAPI unchanged.
const ast = await openapiTS(openapi, {
  defaultNonNullable: false,
  inject: 'export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };',
  transform(_schema, metadata) {
    if (metadata.path === '#/components/schemas/JsonValue') {
      return ts.factory.createTypeReferenceNode('JsonValue');
    }
  },
});

function rewriteRefs(value) {
  if (Array.isArray(value)) return value.map(rewriteRefs);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key,
      key === '$ref' && typeof item === 'string'
        ? item.replace('#/components/schemas/', '#/$defs/')
        : rewriteRefs(item),
    ]));
  }
  return value;
}
const validation = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: 'urn:chinook:public-contract',
  $defs: rewriteRefs(openapi.components.schemas),
};
const files = new Map([
  ['openapi.json', JSON.stringify(openapi, null, 2) + '\n'],
  ['schema.ts', '// Generated by npm run contracts:sync. Do not edit by hand.\n' + astToString(ast)],
  ['validation-schema.json', JSON.stringify(validation, null, 2) + '\n'],
]);
const target = path.join(webRoot, 'src/contracts/generated');
if (!process.argv.includes('--check')) await mkdir(target, { recursive: true });
for (const [name, content] of files) {
  const destination = path.join(target, name);
  if (process.argv.includes('--check')) {
    let existing;
    try { existing = await readFile(destination, 'utf8'); } catch { existing = null; }
    if (existing !== content) throw new Error(`Contract drift: ${name}. Run npm run contracts:sync and review the diff.`);
  } else {
    // Mechanical generation only; authored source uses apply_patch.
    await writeFile(destination, content, 'utf8');
  }
}
console.log(`Public contract ${process.argv.includes('--check') ? 'checked' : 'generated'}: ${schemaNames.length} schemas, 3 artifacts; no backend startup.`);
